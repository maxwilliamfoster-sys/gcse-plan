import json, pathlib
root = pathlib.Path(__file__).parent
src = root / 'src'

# Weekly YouTube videos come from the Study Plan repo's scraper (GCSE-Timetable/videos). The snapshot in
# src/d-videos.js is committed, so the build still works without that repo.
SUB = {'M': 'maths', 'S': 'science', 'H': 'hist', 'G': 'german', 'LIT': 'englit', 'LANG': 'englang'}
vj = root.parent / 'GCSE-Timetable' / 'videos' / 'videos.json'
if vj.exists():
    slim = {}
    for k, vs in json.loads(vj.read_text(encoding='utf8')).items():
        if not vs: continue
        ph, wk, code = k.split('-')
        slim[ph + '-' + wk + '-' + SUB[code]] = [{f: v[f] for f in ('id', 'title', 'channel', 'length')} for v in vs]
    body = '{\n' + ',\n'.join(json.dumps(k) + ':' + json.dumps(v, ensure_ascii=False) for k, v in slim.items()) + '\n}'
    body = body.replace('</', '<\\/')
    (src / 'd-videos.js').write_text('/* Generated by build.py from GCSE-Timetable/videos/videos.json: "<phase>-<week>-<subject>" -> videos. */\nRG.videos = ' + body + ';\n', encoding='utf8')

shell = (src / 'shell.html').read_text(encoding='utf8')
# Basecoat 1.0.2 (MIT, github.com/hunvreus/basecoat): shadcn/ui components as plain CSS classes, vendored so the app works offline
css = (src / 'vendor' / 'basecoat.css').read_text(encoding='utf8') + '\n' + (src / 'app.css').read_text(encoding='utf8')
DATA = ['d-maths.js', 'd-science.js', 'd-english.js', 'd-humanities.js', 'd-german.js', 'd-specref.js', 'd-given.js', 'd-vocab.js', 'd-decks.js', 'd-timetable.js', 'd-focus.js', 'd-videos.js']
data = '\n'.join((src / f).read_text(encoding='utf8') for f in DATA)
# engine (planner, sync, data model) + bell-time timetable + UI layer
app = '\n'.join((src / f).read_text(encoding='utf8') for f in ['app.js', 'timetable.js', 'ui.js'])
frag = shell.replace('/*CSS*/', css).replace('/*DATA*/', data).replace('/*APP*/', app)

# Claude artifact build (fragment — the artifact host adds <html>/<head>)
dist = root / 'dist'; dist.mkdir(exist_ok=True)
(dist / 'gcse-plan.html').write_text(frag, encoding='utf8')

# Standalone page
full = ('<!doctype html>\n<html lang="en-GB">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        + frag.replace('<header', '</head>\n<body>\n<header', 1) + '\n</body>\n</html>\n')
(dist / 'index.html').write_text(full, encoding='utf8')

# GitHub Pages build (served from /docs): home-screen icon, manifest, Firebase sign-in
head_links = ('<link rel="manifest" href="manifest.webmanifest">\n'
              '<link rel="apple-touch-icon" href="icon-180.png">\n'
              '<link rel="icon" type="image/png" href="icon-192.png">\n'
              '<script src="firebase-config.js"></script>\n')
pages = full.replace('<meta name="theme-color"', head_links + '<meta name="theme-color"', 1)
fb = (src / 'firebase.mjs').read_text(encoding='utf8')
pages = pages.replace('\n</body>', '\n<script type="module">\n' + fb + '</script>\n</body>', 1)
(root / 'docs').mkdir(exist_ok=True)
(root / 'docs' / 'index.html').write_text(pages, encoding='utf8')
cfg = root / 'docs' / 'firebase-config.js'
if not cfg.exists():
    cfg.write_text('// Paste the Firebase web config here to switch on accounts + sync.\nwindow.FIREBASE_CONFIG = null;\n', encoding='utf8')
print('built', len(frag) // 1024, 'KB')
